#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
LOCAL_TW="${HOME}/.silk/cache/tailwind/4.3.5/f3f4f5d1727e2b693b8f1c9a1492b5dd87008c86ea286bee1589cb458e6235fc/macos-arm64"

if [ -x "$LOCAL_TW" ]; then
  "$LOCAL_TW" \
    --cwd "$ROOT_DIR" \
    --input "$ROOT_DIR/styles/input.css" \
    --output "$ROOT_DIR/styles/app.css" \
    --minify
elif command -v tailwindcss >/dev/null 2>&1; then
  tailwindcss \
    --cwd "$ROOT_DIR" \
    --input "$ROOT_DIR/styles/input.css" \
    --output "$ROOT_DIR/styles/app.css" \
    --minify
else
  npx --yes @tailwindcss/cli@4.3.5 \
    --cwd "$ROOT_DIR" \
    --input "$ROOT_DIR/styles/input.css" \
    --output "$ROOT_DIR/styles/app.css" \
    --minify
fi

python3 - "$ROOT_DIR/styles/app.css" "$ROOT_DIR/src/app_css.silk" << 'PY'
import sys

css_path, out_path = sys.argv[1], sys.argv[2]
with open(css_path, "r", encoding="utf-8") as f:
    css = f.read()

escaped = (
    css.replace("\\", "\\\\")
       .replace('"', '\\"')
       .replace("\n", "\\n")
       .replace("\r", "")
       .replace("\t", "\\t")
)

with open(out_path, "w", encoding="utf-8") as f:
    f.write("//! Auto-generated by scripts/build-css.sh from styles/input.css via Tailwind CSS v4.\n")
    f.write(f'pub const APP_CSS: string<\'static> = "{escaped}"\n')

print(f"Generated {out_path} ({len(css)} bytes of compiled Tailwind CSS)")
PY
